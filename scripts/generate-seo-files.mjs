// Generates web/app/public/sitemap.xml and robots.txt from the project IA
// (docs/seo.md). Generated, never hand-edited: web/app/prebuild.sh runs this
// before every build and test, so the emitted files always track the manifest.
//
// What goes in:
// - sitemap.xml: the routable public pages — "/" (whatever owns it: the
//   manifest home or the active pack's home surface) plus every marketing
//   page in repobot.project.json. Signed-in and journey routes never appear.
// - robots.txt: allows everything except the kernel's signed-in/journey
//   routes and the manifest's dashboard destinations.
//
// Canonical host: absolute sitemap URLs need the deployed origin. The
// platform's deploy pipeline knows it as APP_BASE_URL (env.manifest.json);
// this script reads SITE_BASE_URL, then APP_BASE_URL, then --base-url. When
// none is set (sandbox, kernel checkout) the sitemap falls back to
// root-relative <loc> paths — valid XML, upgraded to absolute automatically
// on the first build where the platform exports the host — and robots.txt
// omits its Sitemap line (that directive must be absolute).
//
// Usage:
//   node scripts/generate-seo-files.mjs [--base-url https://example.com] [repoRoot]

import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

/**
 * Kernel routes that must never be crawled: auth entry points, the signed-in
 * exemplar app, the checkout/subscription journeys, and the style guide.
 * Kept here (not parsed from Router.ts) because these are stable kernel
 * contracts; manifest dashboard destinations are appended per project.
 */
export const KERNEL_DISALLOWED_PATHS = [
    "/login",
    "/signup",
    "/forgot-password",
    "/reset-password",
    "/magic-link",
    "/users",
    "/projects",
    "/settings",
    "/subscribe",
    "/billing/",
    "/checkout/",
    "/theme",
]

const GENERATED_NOTE =
    "Generated by scripts/generate-seo-files.mjs from repobot.project.json - do not hand-edit (docs/seo.md)."

/**
 * The routable public pages, from the parsed repobot.project.json: "/" always
 * (the manifest home or the active pack's home surface owns it), plus every
 * declared marketing page. Deduped, "/" first, then manifest order.
 */
export function collectPublicPaths(manifest) {
    const paths = ["/"]
    const pages = manifest?.marketing?.pages
    if (Array.isArray(pages)) {
        for (const page of pages) {
            if (typeof page?.path === "string" && page.path.startsWith("/") && !paths.includes(page.path)) {
                paths.push(page.path)
            }
        }
    }
    return paths
}

/** Kernel journey routes plus the manifest's dashboard destination paths. */
export function collectDisallowedPaths(manifest) {
    const paths = [...KERNEL_DISALLOWED_PATHS]
    const destinations = manifest?.dashboard?.destinations
    if (Array.isArray(destinations)) {
        for (const destination of destinations) {
            if (
                typeof destination?.path === "string" &&
                destination.path.startsWith("/") &&
                !paths.includes(destination.path)
            ) {
                paths.push(destination.path)
            }
        }
    }
    return paths
}

function escapeXml(value) {
    return value
        .replace(/&/g, "&amp;")
        .replace(/</g, "&lt;")
        .replace(/>/g, "&gt;")
        .replace(/"/g, "&quot;")
        .replace(/'/g, "&apos;")
}

/** Absolute <loc> URLs when the base URL is known; root-relative otherwise. */
export function buildSitemapXml(paths, baseUrl) {
    const trimmedBase = typeof baseUrl === "string" ? baseUrl.replace(/\/+$/, "") : undefined
    const urls = paths
        .map((pagePath) => {
            const loc = trimmedBase !== undefined ? `${trimmedBase}${pagePath}` : pagePath
            return `    <url>\n        <loc>${escapeXml(loc)}</loc>\n    </url>`
        })
        .join("\n")
    const hostNote =
        trimmedBase === undefined
            ? "\n<!-- No canonical host was set (SITE_BASE_URL / APP_BASE_URL): locs are root-relative until a deploy build provides one. -->"
            : ""
    return `<?xml version="1.0" encoding="UTF-8"?>
<!-- ${GENERATED_NOTE} -->${hostNote}
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls}
</urlset>
`
}

/** Allow everything except the disallowed paths; Sitemap line when the host is known. */
export function buildRobotsTxt(disallowedPaths, baseUrl) {
    const trimmedBase = typeof baseUrl === "string" ? baseUrl.replace(/\/+$/, "") : undefined
    const lines = [
        `# ${GENERATED_NOTE}`,
        "User-agent: *",
        ...disallowedPaths.map((pagePath) => `Disallow: ${pagePath}`),
    ]
    if (trimmedBase !== undefined) {
        lines.push(`Sitemap: ${trimmedBase}/sitemap.xml`)
    }
    return lines.join("\n") + "\n"
}

/** Resolve the canonical host: --base-url flag, then SITE_BASE_URL, then APP_BASE_URL. */
export function resolveBaseUrl(argv, env) {
    const flagIndex = argv.indexOf("--base-url")
    const candidate =
        (flagIndex !== -1 ? argv[flagIndex + 1] : undefined) ?? env.SITE_BASE_URL ?? env.APP_BASE_URL
    if (typeof candidate !== "string" || candidate.trim() === "") {
        return undefined
    }
    try {
        return new URL(candidate).origin
    } catch {
        console.warn(`[generate-seo-files] ignoring invalid base URL: ${candidate}`)
        return undefined
    }
}

function main() {
    const argv = process.argv.slice(2)
    const positional = argv.filter((arg, index) => !arg.startsWith("--") && argv[index - 1] !== "--base-url")
    const repoRoot = positional[0] ?? path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
    const manifestPath = path.join(repoRoot, "repobot.project.json")
    let manifest
    try {
        manifest = JSON.parse(readFileSync(manifestPath, "utf8"))
    } catch {
        manifest = undefined
    }
    const baseUrl = resolveBaseUrl(argv, process.env)
    const outDir = path.join(repoRoot, "web", "app", "public")
    mkdirSync(outDir, { recursive: true })
    writeFileSync(path.join(outDir, "sitemap.xml"), buildSitemapXml(collectPublicPaths(manifest), baseUrl))
    writeFileSync(path.join(outDir, "robots.txt"), buildRobotsTxt(collectDisallowedPaths(manifest), baseUrl))
    console.log(
        `[generate-seo-files] wrote sitemap.xml + robots.txt (${baseUrl ?? "no canonical host - relative locs"}).`,
    )
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    main()
}
