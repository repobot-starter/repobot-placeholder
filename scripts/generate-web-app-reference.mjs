#!/usr/bin/env node
// Generates docs/web-app-content.md — the app kernel field guide agents read
// instead of exploring web/design-system component sources. Companion to
// generate-landing-reference.mjs: setup runs building the signed-in app
// (dashboard checkpoints) get this inlined the way marketing checkpoints get
// the landing reference, so the run starts composing instead of re-deriving
// component contracts turn by turn.
//
//   node scripts/generate-web-app-reference.mjs           # write the doc
//   node scripts/generate-web-app-reference.mjs --check   # verify freshness
//
// The --check mode regenerates in memory and diffs against the committed
// file, so check:all catches a kernel change that forgot to regenerate.

import { readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { componentBlurb, exportedDeclarationNames, extractDeclaration } from "./lib/reference-extract.mjs"

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const DESIGN_SYSTEM_DIR = path.join(ROOT, "web/design-system/src")
const OUTPUT_PATH = path.join(ROOT, "docs/web-app-content.md")

// The dashboard vocabulary, in composition order: page scaffolding first,
// then the list-page spine, then the widgets. Internals (ErrorBoundary,
// GlobalErrors, DataTableColumnManager, ChartCardChart) and the auth surface
// (AuthShell/AuthCard — kernel-owned, themed via tokens, never recomposed)
// are deliberately absent.
const componentModules = [
    "components/AppShell",
    "components/PageLoadingGate",
    "components/UiQueryView",
    "components/UiQueryViewFormModal",
    "components/DataTable",
    "components/FiltersToolbar",
    "components/ListDetailLayout",
    "components/DetailPage",
    "components/StatCard",
    "components/ChartCard",
    "components/ActivityFeed",
    "components/Timeline",
    "components/EmptyState",
    "components/SettingsGroups",
    "components/Skeleton",
    "components/Toast",
    "components/AiChatThread",
    "forms/SchemaFormRuntime",
    "forms/parseSchemaForm",
]

function moduleSource(module) {
    const base = path.join(DESIGN_SYSTEM_DIR, module)
    try {
        return readFileSync(`${base}.tsx`, "utf8")
    } catch {
        return readFileSync(`${base}.ts`, "utf8")
    }
}

const componentBlocks = componentModules.map((module) => {
    const source = moduleSource(module)
    const name = module.split("/").pop()
    const blurb = componentBlurb(source, name)
    const declarations = exportedDeclarationNames(source)
        .map((declarationName) => extractDeclaration(source, declarationName))
        .filter(Boolean)
    if (declarations.length === 0) {
        console.error(`No exported declarations found in ${module} — module moved or renamed?`)
        process.exit(1)
    }
    return [
        `### \`${name}\``,
        blurb ? `\n${blurb}\n` : "",
        "\n```ts\n" + declarations.join("\n\n") + "\n```\n",
    ].join("")
})

const generatedDoc = `# App kernel reference

> Generated by \`scripts/generate-web-app-reference.mjs\` from
> \`web/design-system/src/\` — do not edit by hand. Regenerate with
> \`npm run codegen:web-app-reference\`.

This is the complete signed-in app vocabulary: every dashboard component's
props contract and the schema-form runtime. **These facts are generated from
this kernel's sources and are complete — do not re-verify them by opening
\`web/design-system\` sources or auditing the test suite.**

## How dashboard pages are built

Location: \`web/app/\`. React 19 + Vite + react-router v7 + Apollo. Exemplar
pages: \`web/app/src/View/QueryView/Pages/Projects/\` and
\`web/app/src/View/QueryView/Pages/Users/\`.

A list page for an entity is three files feeding \`UiQueryView\`:

1. Fragments/queries/mutations go in
   \`web/app/src/Graphql/Operations/Gql/<Domain>.ts\` — the ONLY place
   \`gql\` documents live — then \`npm run codegen\` produces typed hooks.
2. \`web/app/src/View/QueryView/Pages/<Entities>/\` holds
   \`<Entities>Page.tsx\` (thin: renders \`UiQueryView\` with the view
   model), \`<Entities>ViewModel.ts\` (query hook, search/filter state, form
   schema queries, mutation handlers), and \`<Entities>Columns.tsx\` (typed
   column defs).
3. Create/edit modals come from the backend form schemas — pass them to
   \`UiQueryViewFormModal\`; submit with
   \`{ idempotencyKey: crypto.randomUUID(), fields }\` and refetch the
   connection query after mutating. Never hand-build entity forms.
4. Register the route in \`web/app/src/Config/Router.ts\` and the nav item
   in the shell config \`web/app/src/View/Navbar/shellNavSections.tsx\`.

Apollo's normalized cache is on (row ids are globally unique). Do not switch
queries to \`no-cache\`; after mutations, refetch the affected connection
queries. The runtime attaches \`Authorization: Bearer <token>\`;
\`currentUser\` hydrates the signed-in user.

The auth surface (\`AuthShell\`/\`AuthCard\`) is kernel-owned and themed
through tokens — never recompose or eject it for a dashboard checkpoint.

## Ejecting and overrides

Never edit \`web/design-system/\` — the pristine guard fails the build. When
props and theme tokens aren't enough:

1. Copy the component into \`web/app/src/Theme/overrides/<Component>/\`.
2. Re-point the export in \`web/app/src/Theme/ui.ts\` (explicit exports win
   over the \`export * from "@base/design-system"\` baseline).
3. Keep props compatible.

## Component contracts

${componentBlocks.join("\n")}`

// check:all runs prettier over docs/**/*.md, so emit prettier-clean output.
const prettier = await import("prettier")
const prettierConfig = (await prettier.resolveConfig(OUTPUT_PATH)) ?? {}
const formattedDoc = await prettier.format(generatedDoc, {
    ...prettierConfig,
    parser: "markdown",
})

const isCheck = process.argv.includes("--check")
if (isCheck) {
    let existing = ""
    try {
        existing = readFileSync(OUTPUT_PATH, "utf8")
    } catch {
        console.error("docs/web-app-content.md is missing — run: npm run codegen:web-app-reference")
        process.exit(1)
    }
    if (existing !== formattedDoc) {
        console.error("docs/web-app-content.md is stale — run: npm run codegen:web-app-reference")
        process.exit(1)
    }
    console.log("docs/web-app-content.md is fresh.")
} else {
    writeFileSync(OUTPUT_PATH, formattedDoc)
    console.log(`Wrote ${path.relative(ROOT, OUTPUT_PATH)} (${componentModules.length} modules).`)
}
